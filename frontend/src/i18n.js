const PLACEHOLDER_RE = /\{(\w+)\}/g;

// Pure t(): looks up a key in the locale dict, falls back to en-US, then
// to the key literal. Interpolates {placeholder} from params.
export function t(locale, key, params) {
  const dict = STRINGS[locale] || STRINGS["en-US"];
  let s = dict[key];
  if (s === undefined) s = STRINGS["en-US"][key];
  if (s === undefined) return key;
  if (!params) return s;
  return String(s).replace(PLACEHOLDER_RE, (m, name) => (name in params ? String(params[name]) : m));
}

export const LOCALES = Object.freeze(["en-US", "ko"]);
const LOCALE_KEY = "cc_locale";

// The one locale reader: App's first render and every api.js call. It reads
// through safe-storage, because a browser that blocks site data throws on
// the bare localStorage getter and the first render used to crash on it, and
// it accepts only a locale the app has strings for (api.js's old copy sent
// any stored text to the server).
export function detectLocale() {
  if (typeof window === "undefined") return "en-US";
  const stored = safeGet(LOCALE_KEY);
  if (stored && LOCALES.includes(stored)) return stored;
  let nav = "";
  try { nav = String(window.navigator?.language || "").toLowerCase(); } catch { nav = ""; }
  if (nav.startsWith("ko")) return "ko";
  return "en-US";
}

// Saves the student's pick; with storage blocked it holds for this page load.
export function saveLocale(locale) {
  if (!LOCALES.includes(locale)) return false;
  return safeSet(LOCALE_KEY, locale);
}
